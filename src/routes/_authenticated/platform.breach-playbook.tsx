const PLAYBOOK = `## 1. النطاق والتعريف
حادثة بيانات هي أي وصول أو إفصاح أو إتلاف أو فقدان غير مصرّح به لبيانات شخصية أو بيانات مشاريع محفوظة في ركيز، سواء نتج عن خطأ تشغيلي أو خلل تقني أو فعل خارجي.

## 2. الأدوار
| الدور | المسؤولية |
| --- | --- |
| مكتشف الحادثة | التبليغ الفوري خلال ساعة عبر شاشة حوادث البيانات دون محاولة معالجة منفردة |
| مسؤول الخصوصية (compliance) | قيادة الاستجابة، تقدير الأثر، قرار الإبلاغ للجهة المختصة وأصحاب البيانات |
| المشرف العام (superadmin) | إجازة إجراءات الاحتواء الحادة مثل تعطيل حساب أو سحب صلاحية أو إيقاف تكامل |
| الدعم | التواصل مع الكيانات المتأثرة بنص معتمد فقط |

## 3. مستويات الخطورة
- **حرجة**: تسرب بيانات مالية أو مواقع دقيقة أو وسائط 360 غير مموّهة، أو وصول متعدد الكيانات.
- **عالية**: كشف بيانات شخصية لهوية مستخدم واحد أو مستندات مشروع خارج جمهورها.
- **متوسطة**: كشف بيانات وصفية غير حساسة، أو صلاحية زائدة اكتُشفت قبل استغلالها.
- **منخفضة**: محاولة فاشلة أو خلل بلا وصول فعلي، تُسجَّل للتعلّم فقط.

## 4. الخط الزمني للاستجابة
1. **خلال ساعة**: تسجيل الحادثة (العنوان، الخطورة، النطاق المتأثر، فئات البيانات، تقدير عدد الأشخاص).
2. **خلال 6 ساعات**: الاحتواء — إبطال الجلسات، سحب المنح، تعطيل التكامل المتأثر، تجميد المشروع عند اللزوم، وتسجيل وقت الاحتواء.
3. **خلال 24 ساعة**: التحليل الجذري الأولي وتحديد ما إذا كان الإبلاغ مطلوبًا.
4. **خلال 72 ساعة**: إبلاغ الجهة المختصة إذا كانت الحادثة تُرجّح ضررًا على أصحاب البيانات، ثم إشعار المتأثرين بلغة عربية واضحة.
5. **خلال 14 يومًا**: إغلاق الحادثة بتسجيل الدروس المستفادة والإجراءات الوقائية.

## 5. الأدلة التي لا تُمسّ
سجلات التدقيق (permission_audit_log، report_audit_log، سجلات أحداث طلبات الخصوصية، سجلات التكاملات) للقراءة فقط ولا تُعدَّل ولا تُحذف أثناء التحقيق. الدفتر المالي append-only ولا يُصحّح إلا بقيد عكسي جديد.

## 6. ما لا يجوز مطلقًا
- إخفاء الحادثة أو تأخير تسجيلها لحين اكتمال الحل.
- نسخ بيانات متأثرة إلى أدوات خارجية أو مراسلات غير رسمية أثناء التحقيق.
- إرسال قيم أسرار أو مفاتيح ضمن وصف الحادثة — الوصف نصي فقط.
- إغلاق حادثة حرجة بلا سبب جذري مكتوب ودرس مستفاد مسجَّل.

## 7. بعد الإغلاق
كل حادثة حرجة أو عالية تُراجَع مقابل سجل الأنشطة وسجل تقييم الأثر، ويُحدَّث الضابط المتأثر أو تُضاف ضوابط جديدة قبل اعتبار الحادثة منتهية.`;

